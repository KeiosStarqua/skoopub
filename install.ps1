function Ensure-RegisteredRepos
{
    param([string] $Manifest, [switch] $Background)

    if (-not (Test-Path -LiteralPath $Manifest))
    {
        Write-Ok "$Manifest not found - skipping registered repo clones"
        return
    }
    try
    {
        $data = Get-Content -Raw -LiteralPath $Manifest | ConvertFrom-Json
    } catch
    {
        Write-Host "    Could not read $Manifest (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
        return
    }
    $reposDir = Join-Path $env:USERPROFILE 'repos'
    New-Item -ItemType Directory -Force -Path $reposDir | Out-Null
    $gitExe = (Get-Command git -ErrorAction SilentlyContinue)
    if (-not $gitExe) { Write-Host '    git not on PATH - skipping registered repo clones' -ForegroundColor Yellow; return }

    foreach ($entry in @($data.repos))
    {
        if (-not $entry.name) { continue }
        if (-not $entry.url)
        {
            Write-Ok "$($entry.name) has no origin - nothing to clone"
            continue
        }
        $target = Join-Path $reposDir $entry.name
        if (Test-Path -LiteralPath (Join-Path $target '.git'))
        {
            Write-Ok "$($entry.name) already cloned at $target"
            continue
        }
        if (Test-Path -LiteralPath $target)
        {
            Write-Host "    $target exists but is not a git checkout - skipping" -ForegroundColor Yellow
            continue
        }
        $cloneArgs = @('clone')
        if ($entry.branch) { $cloneArgs += @('-b', $entry.branch) }
        $cloneArgs += @($entry.url, $target)
        Write-Step "Cloning $($entry.name) into $target"
        if ($Background)
        {
            # Clones are independent and slow (network + disk), so they must not
            # stall the phases behind them. Start them all, report at the end.
            $log = Join-Path $env:LOCALAPPDATA ('skoop\repo-clone-{0}.log' -f $entry.name)
            $argLine = ($cloneArgs | ForEach-Object { if ($_ -match '\s') { '"' + $_ + '"' } else { $_ } }) -join ' '
            try
            {
                $proc = Start-Process -FilePath $gitExe.Source -ArgumentList $argLine -RedirectStandardOutput $log `
                    -RedirectStandardError ($log + '.err') -NoNewWindow -PassThru
                $script:RepoCloneJobs += [pscustomobject]@{ Name = $entry.name; Target = $target; Log = $log; Process = $proc }
                Write-Ok "$($entry.name) cloning in the background - install continues (log: $log)"
            } catch
            {
                Write-Host "    could not start the $($entry.name) clone (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
            }
            continue
        }
        # git writes progress to stderr; merge through cmd so PowerShell 5.1
        # does not raise a terminating NativeCommandError under ErrorAction=Stop.
        $quoted = (@($cloneArgs) | ForEach-Object { '"' + $_ + '"' }) -join ' '
        $out = (& cmd /c ('"{0}" {1} 2>&1' -f $gitExe.Source, $quoted) | Out-String)
        if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath (Join-Path $target '.git')))
        {
            Write-Host "    clone failed for $($entry.name) (non-fatal): $(($out -split "`r?`n" | Select-Object -Last 2) -join ' ')" -ForegroundColor Yellow
        } else
        {
            Write-Ok "cloned $($entry.name)"
        }
    }
}

function Complete-RegisteredRepoClones
{
    # Report the clones started by `Ensure-RegisteredRepos -Background`. Called
    # near the end of the install; failures stay non-fatal.
    if (-not $script:RepoCloneJobs -or $script:RepoCloneJobs.Count -eq 0) { return }
    Write-Step 'Checking the background repo clones'
    foreach ($job in $script:RepoCloneJobs)
    {
        try { $job.Process.WaitForExit() } catch { }
        if (Test-Path -LiteralPath (Join-Path $job.Target '.git'))
        {
            Write-Ok "cloned $($job.Name)"
            continue
        }
        $tail = @()
        # Parenthesise the second element: `@($a, $a + '.err')` parses as
        # `(@($a, $a)) + '.err'`, so the .err log would never be read.
        foreach ($path in @($job.Log, ($job.Log + '.err')))
        {
            if (Test-Path -LiteralPath $path)
            {
                $tail += @(Get-Content -LiteralPath $path -Tail 2 -ErrorAction SilentlyContinue)
            }
        }
        $detail = ($tail | ForEach-Object { $_.ToString().Trim() } | Where-Object { $_ } | Select-Object -Last 2) -join ' '
        Write-Host "    clone failed for $($job.Name) (non-fatal): $detail" -ForegroundColor Yellow
    }
    $script:RepoCloneJobs = @()
}

function Start-HerdrInRio
{
    # Open the terminal first with Herdr already running, so a fresh machine is
    # usable straight after the essentials phase. Kept non-fatal and idempotent.
    if ($NoAutoHerdr -or $env:SKOOP_NO_AUTO_HERDR -eq '1')
    {
        Write-Ok 'Herdr auto-launch disabled (-NoAutoHerdr)'
        return
    }
    if (-not [Environment]::UserInteractive)
    {
        Write-Ok 'non-interactive shell - skipping the Rio/Herdr launch'
        return
    }
    if ($env:HERDR_ENV -eq '1')
    {
        # install.ps1 is sometimes run from inside a Herdr pane; launching a
        # nested client there makes herdr abort with the inception message.
        Write-Ok 'running inside Herdr - skipping the nested Rio/Herdr launch'
        return
    }
    # Re-runs must not stack Rio/Herdr windows on the desktop.
    if (Get-Process -Name 'rio' -ErrorAction SilentlyContinue)
    {
        Write-Ok 'Rio is already open - skipping the auto-launch'
        return
    }
    Update-SkoopProcessPath
    $rioPath = Get-SkoopExePath -Name rio
    $pwshPath = Get-SkoopExePath -Name pwsh
    if (-not $rioPath -or -not $pwshPath)
    {
        Write-Host '    Rio or pwsh not found in PATH/Scoop shims - skipping the auto-launch' -ForegroundColor Yellow
        return
    }
    $reposDir = Join-Path $env:USERPROFILE 'repos'
    if (-not (Test-Path -LiteralPath $reposDir))
    {
        New-Item -ItemType Directory -Force -Path $reposDir | Out-Null
    }
    # Clear markers inherited from a Herdr pane: shell/profile.ps1 does this
    # for new pwsh sessions too, but the child may be launched from a launcher.
    foreach ($name in @(
            'HERDR_ENV', 'HERDR_PANE_ID', 'HERDR_TAB_ID',
            'HERDR_WORKSPACE_ID', 'HERDR_SOCKET_PATH', 'HERDR_BIN_PATH'
        ))
    {
        Remove-Item "Env:$name" -ErrorAction SilentlyContinue
    }
    Write-Step "Opening Rio in $reposDir with Herdr"
    try
    {
        # Rio's -e command must be the last argument; run herdr through pwsh so
        # the repo-managed profile loads (and scrubs any leftover Herdr vars).
        $rioArgs = @('-w', "`"$reposDir`"", '-e', "`"$pwshPath`"", '-NoLogo', '-NoExit', '-Command', 'herdr')
        Start-Process -FilePath $rioPath -ArgumentList $rioArgs -WorkingDirectory $reposDir | Out-Null
        Write-Ok 'Rio opened - Herdr is starting in it'
    } catch
    {
        Write-Host "    Could not open Rio/Herdr (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
    }
}

