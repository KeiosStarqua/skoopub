function Invoke-TailscaleSetup
{
    # Install + sign in to Tailscale, then restore everything from acer-ubuntu
    # (Vicinae, Pear Desktop, Firefox, Atuin, OpenCode auth, SSH key and the
    # registered repo list) before GitHub auth and any clone. OpenCode and
    # Firefox are installed from their own manifest entries first because their
    # restores need the app (opencode auth import) or the browser profile.
    if (-not $EssentialsOnly)
    {
        Install-OpenCodeBeforeRestore -ScoopExe $scoop -ManifestPath $manifest -Force:$ForceInstall
        Install-FirefoxBeforeRestore -ScoopExe $scoop -ManifestPath $manifest -Force:$ForceInstall
    }
    Start-TailscaleDaemon
    if (-not (Test-Path $tailscaleConfig))
    {
        throw "apps/tailscale/configure.ps1 not found at $tailscaleConfig - cannot restore before GitHub auth."
    }
    Write-Step 'Signing in to Tailscale and restoring the acer-ubuntu backups'
    & $tailscaleConfig -SignIn -BackupUser $BackupUser @restoreSwitches

    $restoreScript = Join-Path $repoRoot 'core\restore-backup.ps1'
    if (Test-Path -LiteralPath $restoreScript)
    {
        # SSH key: restore once per machine (marker), non-fatal.
        $sshRestoreMarker = Join-Path $env:LOCALAPPDATA 'skoop\ssh-restore.done'
        if ($SkipSshRestore -or $env:SKOOP_NO_SSH_RESTORE -eq '1')
        {
            Write-Ok 'SSH key restore skipped (-SkipSshRestore)'
        } elseif (Test-Path -LiteralPath $sshRestoreMarker)
        {
            Write-Ok 'SSH key already restored (marker present)'
        } else
        {
            Write-Step 'Restoring the SSH key from the backup'
            try
            {
                & $restoreScript -Only ssh -User $BackupUser -NoRestart
                New-Item -ItemType Directory -Force -Path (Split-Path -Parent $sshRestoreMarker) | Out-Null
                Set-Content -LiteralPath $sshRestoreMarker -Value (Get-Date -Format o) -Encoding UTF8
            } catch
            {
                Write-Host "    SSH key restore failed (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
            }
        }
        # The restored repo list is what Ensure-RegisteredRepos clones from.
        try
        {
            & $restoreScript -Only repos -User $BackupUser -NoRestart
        } catch
        {
            Write-Host "    Repo list restore failed (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
        }
    } else
    {
        Write-Ok 'core/restore-backup.ps1 not found - skipping the SSH key and repo list restore'
    }

    # Vicinae's restore has just replaced its config/data, so the repo-managed
    # keybinds and autostart are applied on top of the snapshot.
    foreach ($step in @(
            @{ Name = 'Vicinae global shortcut (Ctrl+Space)'; Path = $vicinaeConfig },
            @{ Name = 'Vicinae autostart'; Path = $vicinae }
        ))
    {
        if (-not (Test-Path -LiteralPath $step.Path))
        {
            Write-Ok "$($step.Path) not found - skipping"
            continue
        }
        try
        {
            & $step.Path
        } catch
        {
            Write-Host "    $($step.Name) failed (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
        }
    }

    if (Test-Path $ghAuth)
    {
        Write-Step 'Setting up GitHub authentication before cloning repos'
        try
        {
            & $ghAuth -SkipLogin:$SkipGhLogin
        } catch
        {
            Write-Host "    GitHub auth setup failed (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
        }
    } else
    {
        Write-Ok 'apps/github/setup-auth.ps1 not found - skipping'
    }

    Ensure-SkoopClone
    if (-not $SkipRepoClones -and $env:SKOOP_NO_REPO_CLONES -ne '1')
    {
        # A list restored from acer-ubuntu takes precedence over the copy shipped
        # in the checkout, so a fresh machine clones the latest registered repos.
        $reposManifest = Join-Path $env:LOCALAPPDATA 'skoop\repos.json'
        if (-not (Test-Path -LiteralPath $reposManifest))
        {
            $reposManifest = Join-Path $repoRoot 'manifests\repos.json'
        }
        # Repos clone in the background so the phases behind them are not held up;
        # Complete-RegisteredRepoClones reports the outcome before the summary.
        Ensure-RegisteredRepos -Manifest $reposManifest -Background
    }
}

