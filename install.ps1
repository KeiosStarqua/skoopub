function Show-TailscaleSignInHint
{
    # Tailscale's daemon and tray app work without the CLI; only peer listing
    # needs it. Probe the CLI so the sign-in advice matches this machine, and
    # never let a broken CLI fail the bootstrap.
    $tailscale = Get-SkoopExePath -Name tailscale
    if (-not $tailscale)
    {
        Write-Host '    Tailscale CLI not found - sign in from the Tailscale tray icon.' -ForegroundColor Yellow
        return
    }
    $raw = (& cmd /c ('"{0}" status 2>&1' -f $tailscale) | Out-String)
    $exit = $LASTEXITCODE
    # A logged-out node makes `tailscale status` exit 1 too, but that is a
    # normal "not signed in" state, not a daemon connectivity failure.
    if ($raw -match 'Logged out|NeedsLogin|not logged in')
    {
        Write-Ok 'Tailscale is running but not signed in - sign in from the tray icon or run `tailscale up`'
        return
    }
    if ($raw -match 'stopped')
    {
        Write-Ok 'Tailscale is stopped - start it from the tray icon or run `tailscale up`'
        return
    }
    if ($exit -ne 0)
    {
        $line = ($raw -split "`r?`n" | Where-Object { $_.Trim() } | Select-Object -First 1)
        if (-not $line)
        { $line = "exit code $exit" 
        }
        Write-Host "    Tailscale CLI cannot reach the daemon ($($line.Trim())); use the tray icon to sign in." -ForegroundColor Yellow
        return
    }
    Write-Ok 'Tailscale is connected'
}

function Start-TailscaleDaemon
{
    # Scoop ships tailscaled but not the Windows service. Prefer the service
    # when the official installer created it; otherwise run the exe from the
    # Scoop app folder directly (there is no tailscaled shim). Also start the
    # tray app from its Scoop Apps Start Menu shortcut (falling back to
    # tailscale-ipn.exe) and register it in HKCU Run via the package's
    # add-startup.reg, so Tailscale comes back after a sign-in/reboot. The
    # shortcut keeps Windows' notification-area identity (and icon) intact.
    # Login is interactive (tray icon or `tailscale up`), so it is left to you.
    Write-Step 'Starting Tailscale'
    $appDir = $null
    foreach ($root in @($env:SCOOP, (Join-Path $env:USERPROFILE 'scoop'), (Join-Path $env:ProgramData 'scoop')))
    {
        if (-not $root) { continue }
        $candidate = Join-Path $root 'apps\tailscale\current'
        if (Test-Path -LiteralPath (Join-Path $candidate 'tailscale.exe'))
        { $appDir = $candidate
          break
        }
    }
    $service = Get-Service -Name 'Tailscale' -ErrorAction SilentlyContinue
    if ($service)
    {
        try
        {
            if ($service.Status -ne 'Running')
            { Start-Service -Name 'Tailscale' 
            }
            Write-Ok 'Tailscale service is running'
        } catch
        {
            Write-Host "    Could not start the Tailscale service (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
        }
        try
        {
            if ((Get-Service -Name 'Tailscale' -ErrorAction SilentlyContinue).StartType -ne 'Automatic')
            {
                Set-Service -Name 'Tailscale' -StartupType Automatic
                Write-Ok 'Tailscale service set to Automatic'
            }
        } catch
        {
            Write-Host "    Could not set Tailscale to Automatic (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
        }
    } else
    {
        $tailscaled = Get-Command tailscaled -ErrorAction SilentlyContinue
        $daemonExe = if ($tailscaled) { $tailscaled.Source } elseif ($appDir) { Join-Path $appDir 'tailscaled.exe' } else { $null }
        if (-not $daemonExe -or -not (Test-Path -LiteralPath $daemonExe))
        {
            Write-Ok 'tailscaled.exe not found - skipping'
        } elseif (Get-Process -Name 'tailscaled' -ErrorAction SilentlyContinue)
        {
            Write-Ok 'tailscaled is already running'
        } else
        {
            try
            {
                Start-Process -FilePath $daemonExe -WindowStyle Hidden
                Write-Ok 'launched tailscaled from Scoop'
            } catch
            {
                Write-Host "    Could not launch tailscaled (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
            }
        }
    }

    if ($appDir)
    {
        $trayExe = Join-Path $appDir 'tailscale-ipn.exe'
        if (Test-Path -LiteralPath $trayExe)
        {
            if (-not (Get-Process -Name 'tailscale-ipn' -ErrorAction SilentlyContinue))
            {
                # Prefer the Start Menu shortcut: Windows keys the tray icon on
                # the shortcut/executable identity, so this keeps the icon and
                # its notifications visible.
                $trayShortcut = Join-Path ([Environment]::GetFolderPath('ApplicationData')) 'Microsoft\Windows\Start Menu\Programs\Scoop Apps\Tailscale.lnk'
                $started = $false
                if (Test-Path -LiteralPath $trayShortcut)
                {
                    try
                    {
                        Start-Process -FilePath $trayShortcut
                        Write-Ok 'started the Tailscale tray from its Scoop Apps shortcut'
                        $started = $true
                    } catch
                    {
                        Write-Host "    Could not start the Tailscale shortcut (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
                    }
                }
                if (-not $started)
                {
                    try
                    {
                        Start-Process -FilePath $trayExe
                        Write-Ok 'started tailscale-ipn.exe (Tailscale tray)'
                    } catch
                    {
                        Write-Host "    Could not start tailscale-ipn.exe (non-fatal): $($_.Exception.Message)" -ForegroundColor Yellow
                    }
                }
            } else
            { Write-Ok 'tailscale-ipn.exe is already running'
            }
            $startupReg = Join-Path $appDir 'add-startup.reg'
            if (Test-Path -LiteralPath $startupReg)
            {
