#Requires -Version 5.1
<#
.SYNOPSIS
    One-shot Windows bootstrap: install Scoop, restore packages, wire up the shell config.

.DESCRIPTION
    - Installs Scoop if it is missing (per-user, or system-wide when run elevated).
    - Makes sure git is available, then installs manifests/scoop.json in the
      ordered phases declared by manifests/phases.json: phase 1 is the fast
      essentials (git, PowerShell 7, Rio first, then the Herdr TUI, Vicinae and
      Tailscale), and the heavy downloads come last. Phase 1 finishes its own
      setup (Rio config, Vicinae shortcut + autostart, Herdr check, Tailscale
      sign-in with `tailscale up --qr`), restores Vicinae once Tailscale is
      connected, and opens Rio in ~/repos with Herdr running before phase 2
      starts. The script re-launches itself under pwsh as soon as phase 1
      installs it. -EssentialsOnly stops right after that phase.
    - Installs the Firefox policy once the apps phase has installed Firefox:
      auto-installs Bitwarden, mymind and "I still don't care about cookies",
      shows the bookmarks toolbar, adds a skoopub bookmarks folder (Hacker News,
      mymind, Scoop, OpenCode, YouTube to Transcript), sets ChatGPT as the
      homepage, and disables Firefox's save-password prompt. Firefox is then
      asked to become the default browser (Windows may ask you to confirm).
      Firefox alone is pinned in scoop.json to 161.0 with Source
      "<auto-generated>" + "Held package", so `scoop import` installs that exact
      version and holds it; run `scoop unhold firefox` before upgrading.
    - Starts Tailscale in phase 1 (Windows service if present, otherwise the
      Scoop `tailscaled` shim) and runs `tailscale up --qr` through
      apps/tailscale/configure.ps1 so the login URL/QR is printed before the
      heavy phases; sign-in is skipped when the node is already connected. The
      CLI may be missing or unable to reach the daemon on Windows, which is
      reported without failing.
    - Tags this device with `tag:public-client` in the tailnet via
      apps/tailscale/configure.ps1 (idempotent, non-fatal when not signed in).
    - Offers a one-prompt Herdr remote setup via apps/herdr/setup-ssh.ps1: pick a
      machine from the tailnet list (or type its IP/MagicDNS name when the CLI
      is not usable), then save it in Herdr (`herdr machine add`) over Tailscale
      SSH so it shows up in your Herdr sidebar. No keys, passwords or machine
      addresses are stored in the repo.
    - Keeps a UniKey that is already installed (e.g. on a public PC) instead of
      adding a second copy; -ForceUniKey installs the Scoop build anyway.
    - Configures UniKey with no GUI via apps/unikey/configure.ps1: Unicode output,
      VNI input method, Vietnamese typing on, no startup dialog and a per-user
      Startup shortcut. Settings come from the sanitized apps/unikey/unikey.reg
      baseline (HKCU\SOFTWARE\PkLong\UniKey for 4.6 RC2); -Export / -Restore
      back up and restore the DWORD settings without machine-specific paths.
    - Sets the CurrentUser execution policy to RemoteSigned so the repo-managed
      profile and other local scripts load instead of failing with "running
      scripts is disabled on this system"; an already-permissive policy is kept.
      A fresh shell is probed afterwards, so a policy/hook regression is reported.
    - Adds a dot-source line for profile.ps1 to your PowerShell $PROFILE early on,
      so zoxide/atuin are configured even if a later, optional step fails.
    - Enables Task Manager by clearing DisableTaskMgr for the current user (and
      machine-wide when elevated); a failure is reported but does not abort.
    - Checks the Windows theme and turns on Dark Mode for apps and the system via
      core/set-dark-mode.ps1; re-runs leave an already-dark theme untouched.
    - Checks first, then only applies what is missing via apps/sharex/fix-printscreen.ps1
      so ShareX owns the PrtSc key; an already-applied fix is left untouched (no registry
      write, no ShareX restart). A failure is reported but does not abort the bootstrap.
    - Copies the repo-managed Zed settings/keymap/tasks into %APPDATA%\Zed (old
      files are backed up); Zed installs its declared extensions on next start.
    - Copies the repo-managed Rio config into %LOCALAPPDATA%\rio\config.toml,
      setting the font size (Rio's zoom) to 16; Rio hot-reloads it on change.
    - Offers to run `gh auth login` (only when needed) and runs `gh auth setup-git`
      so `git push` uses the GitHub CLI token instead of prompting for a username.
    - Sets the global git author identity to Keios <git@taquangkhoi.com> via
      apps/git/setup-identity.ps1, so commits are attributed correctly on every repo.
    - Registers `vicinae-server.exe` in the per-user Startup folder and starts it
      now, so the Vicinae global shortcut works after every sign-in.
    - Sets the Vicinae global toggle shortcut to Ctrl+Space via a repo-managed
      config import (existing Vicinae settings are preserved).
    - Deploys a conflict-free whkdrc and a Komorebi config (tight 4px workspace /
      2px container padding plus initial-workspace rules: Rio/Firefox on 1,
      Zed/VS Code/Pear Desktop on 2, Columns on workspace 1) to ~/.config via
      apps/komorebi/configure.ps1, then starts/reloads whkd (and Komorebi when needed)
      and a watcher that keeps Rio left / Firefox right in the Terminal workspace. It
      also auto-hides the Windows taskbar via apps/komorebi/set-taskbar-autohide.ps1 so
      tiling windows use the full screen (YASB is the visible bar).
    - Deploys the repo-managed YASB status bar (config.yaml, styles.css and a .env
      template) via apps/yasb/configure.ps1 and starts YASB for the Komorebi UI.
    - Adds an `n` alias for Nushell in PowerShell (profile.ps1) and a cmd.exe
      AutoRun doskey macro via apps/nushell/setup.ps1, preserving existing AutoRun entries.
    - Registers a per-user scheduled task (SkoopCleanupOnShutdown) via
      core/install-shutdown-hook.ps1 so the Firefox/Vicinae/Atuin backup and local
      sign-in cleanup (GitHub, Tailscale, Pear Desktop, Firefox) run automatically
      on shutdown/logoff; -BackupUser / SKOOP_BACKUP_USER supplies the SSH user,
      and -SkipShutdownHook opts out.
    - Installs skoopub-mouse from the GitHub Release into %LOCALAPPDATA%\skoop\mouse
      via apps/mouse/configure.ps1 (non-fatal), so `apps/mouse/mouse.ps1 diagnose`
      can capture HID Raw Input vs WM_MOUSEWHEEL. The correction hook is opt-in:
      run `mouse.ps1 fix` / `mouse.ps1 restore` yourself after a diagnosis.
    - Creates ~/repos and clones skoopub into ~/repos\skoopub when it is missing.
      An existing directory is never overwritten, so this is safe to re-run.
    - Installs Rio before Herdr in phase 1, then opens Rio in ~/repos with Herdr
      already running. Skipped for non-interactive shells and Herdr panes;
      -NoAutoHerdr / SKOOP_NO_AUTO_HERDR=1 opts out.
    - Restores Vicinae from the latest acer-ubuntu snapshot right after Tailscale
      connects (via core/restore-backup.ps1 -Only vicinae), with a marker file so
      repeated installs do not re-download it. Non-fatal; supply -BackupUser or
      SKOOP_BACKUP_USER when running unattended.

    By default the script runs the Full setup immediately with no options to
    choose. Pass -Menu (or $env:SKOOP_MENU=1) to open the optional interactive
    menu: Full setup / Essentials only / Configure only / Connect Herdr only /
    Quit, using gum when available and a numbered prompt otherwise. -NoMenu is
    kept as a no-op for older scripts.

    Works two ways:
      Local :  .\install.ps1
      Remote:  irm https://raw.githubusercontent.com/KeiosStarqua/skoopub/main/install.ps1 | iex

    Runs under PowerShell 7 (pwsh) when it is already installed: from Windows
    PowerShell 5.1 the script re-launches itself with the same options via
    `pwsh -NoProfile -File`, so gum's TUI, native stderr and UTF-8 files behave
    correctly. Use -NoPwsh (or $env:SKOOP_NO_PWSH=1) to stay on 5.1, e.g. before
    pwsh is installed. Piped runs cannot re-launch (there is no script file) and
    stay in the shell that evaluates them.

.PARAMETER RepoRawBase
    Raw URL base used to fetch scoop.json / profile.ps1 when the script is piped in
    and there is no local checkout. Override this if you use a fork.

.PARAMETER ForceUniKey
    Install the Scoop UniKey package even if another UniKey is already installed.

.PARAMETER SkipGhLogin
    Skip the interactive `gh auth login` prompt; only wire up an existing gh login.

.PARAMETER HerdrPeer
    Switch: use the interactive gum picker to choose the Herdr machine
    (no value needed). Use -Peer to supply a name/IP non-interactively.

.PARAMETER Peer
    Tailnet IP or MagicDNS name of the Herdr machine. Skips the picker.
    Defaults to $env:SKOOP_HERDR_PEER for piped runs.

.PARAMETER HerdrUser
    SSH user to use on the Herdr machine (otherwise auto-detected).

.PARAMETER SkipHerdrConnect
    Do not run the Herdr remote step (useful for unattended installs).

.PARAMETER Menu
    Open the interactive setup menu (gum when available, numbered prompt
    otherwise). The default is a direct Full setup with no menu (also
    $env:SKOOP_MENU=1 for piped runs).

.PARAMETER NoMenu
    Kept for compatibility; the menu is opt-in now, so a bare `.\install.ps1`
    already runs the full setup without asking.

.PARAMETER EssentialsOnly
    Stop after the core-terminal phase: PowerShell 7, Rio, Vicinae, the Herdr
    TUI and Tailscale sign-in, with their setup finished. Run the script again
    without this switch to install the remaining phases.

.PARAMETER NoGum
    Force the numbered prompt instead of gum (or set $env:SKOOP_NO_GUM=1). Useful
    in terminals where gum cannot draw its TUI.

.PARAMETER NoPwsh
    Do not re-launch under PowerShell 7. Stays on Windows PowerShell 5.1 (also
    $env:SKOOP_NO_PWSH=1).

.PARAMETER NoAutoHerdr
    Do not open Rio with Herdr after the essentials phase (also
    $env:SKOOP_NO_AUTO_HERDR=1). Useful for unattended installs.

.EXAMPLE
    # One command: configure this machine, then pick a tailnet machine and add it to Herdr.
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1

.EXAMPLE
    # Force the interactive peer picker.
    .\install.ps1 -HerdrPeer

    # Same, but with the machine/user supplied so nothing is prompted.
    .\install.ps1 -Peer <machine> -HerdrUser <user> -SkipGhLogin

.EXAMPLE
    irm https://raw.githubusercontent.com/KeiosStarqua/skoopub/main/install.ps1 | iex
#>
[CmdletBinding()]
param(
    [string]$RepoRawBase = 'https://raw.githubusercontent.com/KeiosStarqua/skoopub/main',
    [switch]$ForceUniKey,
    [switch]$SkipGhLogin,
    [switch]$HerdrPeer,
    [string]$Peer = "$env:SKOOP_HERDR_PEER",
    [string]$HerdrUser = "$env:SKOOP_HERDR_USER",
    [switch]$SkipHerdrConnect,
    [switch]$Menu,
    [switch]$NoMenu,
    [switch]$NoGum,
    [switch]$NoPwsh,
    [switch]$NoAutoHerdr,
    [switch]$EssentialsOnly,
    [string]$BackupUser = "$env:SKOOP_BACKUP_USER",
    [switch]$SkipShutdownHook,
    [switch]$Help
)

# Env vars let the piped (`irm ... | iex`) form pass the same options.
if ($env:SKOOP_SKIP_HERDR -eq '1') { $SkipHerdrConnect = $true }
if ($env:SKOOP_ESSENTIALS_ONLY -eq '1') { $EssentialsOnly = $true }
if ($env:SKOOP_NO_AUTO_HERDR -eq '1') { $NoAutoHerdr = $true }
if ($env:SKOOP_MENU -eq '1') { $Menu = $true }
if ($NoGum) { $env:SKOOP_NO_GUM = '1' }

# `--help` arrives in $args with CmdletBinding; handle it before any side effect.
# --help binds to the first positional string parameter ($RepoRawBase) when
# the script is invoked as `& .\install.ps1 --help`, so check that too.
if ($Help -or $RepoRawBase -in @('--help', '-h', '/?', 'help') -or
    ($args | Where-Object { $_ -in @('--help', '-h', '/?', 'help') })) {
    Write-Host @'
skoop install.ps1 - interactive Windows setup

Usage:
  .\install.ps1                          # full setup, no options to choose
  .\install.ps1 -Menu                    # menu: Full / Essentials / Configure / Herdr / Quit
  .\install.ps1 -EssentialsOnly          # only pwsh, Rio, Vicinae and the Herdr TUI
  .\install.ps1 -HerdrPeer              # interactive peer picker
  .\install.ps1 -Peer <machine> -HerdrUser <user>
  .\install.ps1 -SkipHerdrConnect        # configure only
  irm https://raw.githubusercontent.com/KeiosStarqua/skoopub/main/install.ps1 | iex

Options: -ForceUniKey -SkipGhLogin -HerdrPeer -Peer -HerdrUser -SkipHerdrConnect -Menu -NoMenu -NoGum -NoPwsh -NoAutoHerdr -EssentialsOnly -BackupUser -SkipShutdownHook -Help
Piped runs use env vars: SKOOP_HERDR_PEER, SKOOP_HERDR_USER, SKOOP_SKIP_HERDR, SKOOP_MENU, SKOOP_NO_MENU, SKOOP_NO_GUM, SKOOP_NO_PWSH, SKOOP_NO_AUTO_HERDR, SKOOP_ESSENTIALS_ONLY, SKOOP_BACKUP_USER
'@
    return
}

# Prefer PowerShell 7+ when it is installed: Windows PowerShell 5.1 rewrites
# native stderr (gum's TUI becomes a NativeCommandError) and decodes BOM-less
# UTF-8 as ANSI. Phase 1 installs pwsh, so the same check runs again after that
# phase and re-launches the rest of the setup under pwsh. -NoPwsh /
# $env:SKOOP_NO_PWSH=1 stays on 5.1, and a piped `irm ... | iex` run has no
# script file to re-launch.
function Get-SkoopReLaunchArgs {
    param([switch]$SkipMenu)
    $list = @('-NoLogo', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $PSCommandPath)
    if ($SkipMenu -or $NoMenu) { $list += '-NoMenu' }
    if ($Menu -and -not $SkipMenu) { $list += '-Menu' }
    if ($RepoRawBase) { $list += @('-RepoRawBase', $RepoRawBase) }
    if ($ForceUniKey) { $list += '-ForceUniKey' }
    if ($SkipGhLogin) { $list += '-SkipGhLogin' }
    if ($SkipHerdrConnect) { $list += '-SkipHerdrConnect' }
    if ($HerdrPeer) { $list += '-HerdrPeer' }
    if ($EssentialsOnly) { $list += '-EssentialsOnly' }
    if ($NoGum) { $list += '-NoGum' }
    if ($NoAutoHerdr) { $list += '-NoAutoHerdr' }
    if ($SkipShutdownHook) { $list += '-SkipShutdownHook' }
    if ($Peer) { $list += @('-Peer', $Peer) }
    if ($HerdrUser) { $list += @('-HerdrUser', $HerdrUser) }
    if ($BackupUser) { $list += @('-BackupUser', $BackupUser) }
    return $list
}

function Invoke-PwshReLaunch {
    param([switch]$SkipMenu)
    if ($NoPwsh -or $env:SKOOP_NO_PWSH -eq '1' -or $env:SKOOP_PWSH_RELAUNCHED -eq '1') { return $false }
    if ($PSVersionTable.PSEdition -ne 'Desktop') { return $false }
    if (-not $PSCommandPath -or -not (Test-Path -LiteralPath $PSCommandPath)) { return $false }
    $pwsh = Get-Command pwsh -ErrorAction SilentlyContinue
    if (-not $pwsh) { return $false }

    Write-Host '    re-launching under PowerShell 7 (pwsh); pass -NoPwsh to stay on 5.1' -ForegroundColor DarkGray
    # Guard inherited by the child, so a broken pwsh shim cannot loop forever.
    $env:SKOOP_PWSH_RELAUNCHED = '1'
    try {
        & $pwsh.Source @(Get-SkoopReLaunchArgs -SkipMenu:$SkipMenu)
        exit $LASTEXITCODE
    } catch {
        Write-Host "    could not start pwsh ($($_.Exception.Message)) - continuing on Windows PowerShell 5.1" -ForegroundColor Yellow
        return $false
    }
}

$null = Invoke-PwshReLaunch

