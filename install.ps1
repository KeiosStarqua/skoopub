#Requires -Version 5.1
<#
.SYNOPSIS
    One-shot Windows bootstrap: install Scoop, restore packages, wire up the shell config.

.DESCRIPTION
    - Installs Scoop if it is missing (per-user, or system-wide when run elevated).
    - Makes sure git is available, then installs manifests/scoop.json in the
      ordered phases declared by manifests/phases.json: phase 1 is the terminal
      and the Herdr TUI (git, PowerShell 7, Rio first, then Alacritty, WezTerm,
      Herdr, Vicinae and the Nerd Fonts), phase 2 installs and signs in to
      Tailscale, and the heavy downloads come last. Re-runs check which Scoop
      apps are already installed and leave them out of the phase manifests, so
      only missing apps are imported; -ForceInstall re-imports the existing ones.
      Phase 1 finishes its own setup (Rio config, Herdr check) and opens Rio in
      ~/repos with Herdr running before Tailscale. The script opens a new
      PowerShell 7 window as soon as phase 1 installs pwsh. -EssentialsOnly stops right
      after the Tailscale phase. Inside a phase, app imports run in parallel on
      PowerShell 7 (up to -ThrottleLimit, default 4); 1 or 5.1 runs them
      sequentially. Phase order and the per-phase callbacks never change.
    - Installs the Firefox policy once Firefox is installed:
      auto-installs Bitwarden, mymind and "I still don't care about cookies",
      shows the bookmarks toolbar, sets ChatGPT as the homepage, and disables
      Firefox's save-password prompt. Bookmarks come from the restored Firefox
      profile, so no managed bookmark folder is injected. Firefox is then
      asked to become the default browser (Windows may ask you to confirm).
      Firefox alone is pinned in scoop.json to 161.0 with Source
      "<auto-generated>" + "Held package", so `scoop import` installs that exact
      version and holds it; run `scoop unhold firefox` before upgrading.
    - Installs OpenCode and Firefox with Scoop from their manifest entries right
      before the restore pass, so both CLIs/browsers are usable immediately; the
      later phases skip apps that are already installed.
    - Phase 2 installs Tailscale and runs `tailscale up --qr` through
      apps/tailscale/configure.ps1 before any ~/repos clone. The QR opens in a
      new Rio window (a legacy console mangles its Unicode blocks), reuses one
      already showing the QR, and closes itself after sign-in; sign-in is skipped
      when the node is already connected. Once connected it advertises
      tag:public-client BEFORE restoring (the tailnet ACL may only let tagged
      devices reach acer-ubuntu); the restore children pass -SkipTag so it is
      advertised once.
      Once connected it restores everything from acer-ubuntu in one pass
      (Vicinae, Pear Desktop, Firefox, Atuin, OpenCode credentials, SSH key and
      repo list) before the `gh auth login` prompt; if the OpenCode or Firefox
      restore fails, setup stops before GitHub auth and any repo clone unless
      `-SkipFirefoxRestore` was passed. The CLI may be missing or unable to reach
      the daemon on Windows, which is reported without failing.
    - Tags this device with `tag:public-client` in the tailnet via
      apps/tailscale/configure.ps1 (idempotent, non-fatal when not signed in).
    - Offers a one-prompt Herdr remote setup via apps/herdr/setup-ssh.ps1: pick a
      machine from the tailnet list (or type its IP/MagicDNS name when the CLI
      is not usable), then save it in Herdr (`herdr machine add`) over Tailscale
      SSH so it shows up in your Herdr sidebar. No keys, passwords or machine
      addresses are stored in the repo.
    - Keeps a UniKey that is already installed (e.g. on a public PC) instead of
      adding a second copy; -ForceUniKey installs the Scoop build anyway.
    - Configures UniKey with no GUI via apps/unikey/configure.ps1: Unicode output,
      VNI input method, Vietnamese typing on, no startup dialog and a per-user
      Startup shortcut. Settings come from the sanitized apps/unikey/unikey.reg
      baseline (HKCU\SOFTWARE\PkLong\UniKey for 4.6 RC2); -Export / -Restore
      back up and restore the DWORD settings without machine-specific paths.
    - Sets the CurrentUser execution policy to RemoteSigned so the repo-managed
      profile and other local scripts load instead of failing with "running
      scripts is disabled on this system"; an already-permissive policy is kept.
      A fresh shell is probed afterwards, so a policy/hook regression is reported.
    - Adds a dot-source line for profile.ps1 to your PowerShell $PROFILE early on,
      so zoxide/atuin are configured even if a later, optional step fails.
    - Enables Task Manager by clearing DisableTaskMgr for the current user (and
      machine-wide when elevated); a failure is reported but does not abort.
    - Sets marimo's permanent display theme to dark by merging `[display]
      theme = "dark"` into ~/.marimo.toml via apps/marimo/configure.ps1; existing
      settings are preserved and changed originals are backed up.
    - Turns on Dark Mode for apps and the system first (core/set-dark-mode.ps1,
      before Scoop or anything else); re-runs leave an already-dark theme untouched.
    - Checks first, then only applies what is missing via apps/sharex/fix-printscreen.ps1
      so ShareX owns the PrtSc key; an already-applied fix is left untouched (no registry
      write, no ShareX restart). A failure is reported but does not abort the bootstrap.
    - Starts Tailscale and ShareX from their Scoop Apps Start Menu shortcuts at the
      end of the run when they are not already up; failures are non-fatal. After the
      Tailscale sign-in the tray is (re)started from the same shortcut so Windows
      keeps showing its icon and the "Authentication Needed" notification.
    - Copies the repo-managed Zed settings/keymap/tasks into %APPDATA%\Zed (old
      files are backed up); Zed installs its declared extensions on next start.
    - Copies the repo-managed Rio config into %LOCALAPPDATA%\rio\config.toml,
      setting the font size (Rio's zoom) to 16; Rio hot-reloads it on change.
    - Offers to run `gh auth login` (only when needed) and runs `gh auth setup-git`
      before cloning any repo into ~/repos, so private checkouts can authenticate
      and `git push` uses the GitHub CLI token instead of prompting for a username.
    - Sets the global git author identity to Keios <git@taquangkhoi.com> via
      apps/git/setup-identity.ps1, so commits are attributed correctly on every repo.
    - Registers `vicinae-server.exe` in the per-user Startup folder and starts it
      now, so the Vicinae global shortcut works after every sign-in.
    - Sets the Vicinae global toggle shortcut to Ctrl+Space via a repo-managed
      config import (existing Vicinae settings are preserved).
    - Deploys a conflict-free whkdrc and a Komorebi config (tight 3px workspace /
      2px container padding plus initial-workspace rules: Rio/Firefox on 1,
      Zed/VS Code/Pear Desktop/YASB Themes on 2, Columns on workspace 1) to ~/.config via
      apps/komorebi/configure.ps1, then starts/reloads whkd (and Komorebi when needed)
      and a watcher that keeps Rio left / Firefox right in the Terminal workspace. It
      also auto-hides the Windows taskbar via apps/komorebi/set-taskbar-autohide.ps1 so
      tiling windows use the full screen (YASB is the visible bar).
    - Deploys the YASB status bar via apps/yasb/configure.ps1: it downloads the
      chosen theme's config.yaml/styles.css from the community YASB themes
      catalog (default dots windows, id d513044f-9218-46e1-ab62-c15705b80341;
      -ThemeId / SKOOP_YASB_THEME_ID picks another) and writes them to ~/.config/yasb
      with backups, plus a .env template; no theme files are committed here.
      apps/yasb/setup-wallpapers.ps1 shallow-clones D3Ext/aesthetic-wallpapers once
      and points YASB_WALLPAPER_DIR at its images folder. A wallpapers widget is
      added to the bar with Ctrl+Alt+W / Alt+E to open the gallery (Left/Right +
      Enter to apply) and right-click for a random wallpaper; opt out with
      -NoWallpapers / SKOOP_NO_WALLPAPERS=1.
    - Clears wallpaper-change policies (NoChangingWallPaper, NoDispBackgroundPage
      and a forced Wallpaper/WallpaperStyle value) for the current user and, when
      elevated, machine-wide, then sets a desktop wallpaper from the cloned
      collection via SystemParametersInfo (Fill). -Wallpaper <path> picks a
      specific image; -NoWallpaper / SKOOP_NO_WALLPAPER=1 skips both steps.
    - Adds an `n` alias for Nushell in PowerShell (profile.ps1) and a cmd.exe
      AutoRun doskey macro via apps/nushell/setup.ps1, preserving existing AutoRun entries.
    - Registers a per-user scheduled task (SkoopCleanupOnShutdown) via
      core/install-shutdown-hook.ps1 so the Firefox/Vicinae/Atuin/Pear Desktop/
      OpenCode backup and local sign-in cleanup (GitHub, Tailscale, Pear Desktop,
      OpenCode, Firefox) run automatically on shutdown/logoff; -BackupUser /
      SKOOP_BACKUP_USER supplies the SSH user and is cached in
      %LOCALAPPDATA%\skoop\backup-user so later restores do not prompt;
      -SkipShutdownHook opts out.
    - Adds a notification-area icon via apps/tray/configure.ps1 (per-user
      Startup shortcut, started now) whose menu runs the same scripts without a
      terminal: "Backup now" (-BackupOnly) or "Backup + sign out" (the full
      cleanup, after a confirmation). Useful when the desktop is handover-ready
      and no shell can be opened.
    - Installs skoopub-mouse from the GitHub Release into %LOCALAPPDATA%\skoop\mouse
      via apps/mouse/configure.ps1 (non-fatal), so `apps/mouse/mouse.ps1 diagnose`
      can capture HID Raw Input vs WM_MOUSEWHEEL. It also sets the hardware DPI
      of a Logitech HID++ mouse to 1200 via `mouse.ps1 dpi` (hidapi, no G H UB
      config editing); -MouseDpi changes the value, -SkipMouseDpi opts out. Both
      run early, before the Scoop phases, so the pointer is correct right away.
      The correction hook remains opt-in: run `mouse.ps1 fix` / `restore` yourself.
    - Installs and starts LibreScroll (inertial middle-button scrolling) from its
      GitHub release via apps/librescoll/configure.ps1: the SHA-256 digest is
      verified before extracting to %LOCALAPPDATA%\skoop\librescoll, a per-user
      Startup shortcut is written, and the tray app is launched. LibreScroll
      blocks physical wheel events while active, so pause it (tray -> Pause)
      before running skoopub-mouse diagnostics; failures are non-fatal.
    - After Tailscale sign-in and GitHub auth, creates ~/repos and clones skoopub
      into ~/repos\skoopub when it is missing. It also clones the repos registered
      in manifests/repos.json (kirector, tinygrad, …) into ~/repos, skipping
      existing checkouts and repos without an origin. Nothing existing is
      overwritten; -SkipRepoClones / SKOOP_NO_REPO_CLONES=1 opts out.
    - Installs the terminals and Herdr first (phase 1, core-terminal), then opens
      Rio in ~/repos with Herdr already running before Tailscale. Skipped for
      non-interactive shells, Herdr panes and an already-open Rio window;
      -NoAutoHerdr / SKOOP_NO_AUTO_HERDR=1 opts out.
    - Phase 2 installs and signs in to Tailscale (`tailscale up --qr`), then
      restores everything from acer-ubuntu in one pass before GitHub auth and the
      repo clones: Vicinae, Pear Desktop, Firefox, Atuin, OpenCode config/state and
      credentials, the SSH key and the registered repo list (core/restore-backup.ps1
      -Only ssh / -Only repos for the last two). A marker file per app makes
      repeated installs a no-op; Firefox is closed and relaunched around the copy
      and Atuin warns you to close other Atuin shells. The ponytail plugin
      (@dietrichgebert/ponytail) is then added to OpenCode once (via
      `opencode plugin add`), checked against ~/.config/opencode/opencode.json;
      a failure is reported but does not abort the bootstrap.
      Non-fatal, except a missing OpenCode/Firefox snapshot before the clone;
      supply -BackupUser or SKOOP_BACKUP_USER when running unattended.
      -SkipFirefoxRestore / -SkipAtuinRestore opt out (also
      SKOOP_NO_FIREFOX_RESTORE=1 / SKOOP_NO_ATUIN_RESTORE=1);
      -ForceFirefoxRestore / -ForceAtuinRestore repeat one (also
      SKOOP_FORCE_FIREFOX_RESTORE=1 / SKOOP_FORCE_ATUIN_RESTORE=1).

    By default the script runs the Full setup immediately with no options to
    choose. Pass -Menu (or $env:SKOOP_MENU=1) to open the optional interactive
    menu: Full setup / Essentials only / Configure only / Connect Herdr only /
    Quit, using gum when available and a numbered prompt otherwise. -NoMenu is
    kept as a no-op for older scripts.

    Works two ways:
      Local :  .\install.ps1
      Remote:  irm https://raw.githubusercontent.com/KeiosStarqua/skoopub/main/install.ps1 | iex

    Runs under PowerShell 7 (pwsh) when it is already installed: from Windows
    PowerShell 5.1 the script opens a NEW PowerShell 7 window running the same
    options (`pwsh -NoExit -File`), so gum's TUI, native stderr and UTF-8 files
    behave correctly and the calling console is left alone. Use -NoPwsh (or
    $env:SKOOP_NO_PWSH=1) to stay on 5.1, e.g. before pwsh is installed. A piped
    `irm ... | iex` run caches install.ps1 to %LOCALAPPDATA%\skoop\install.ps1 so
    it can re-launch too; after phases are imported the process PATH is rebuilt
    from the registry and executables are resolved from the Scoop roots, so newly
    installed pwsh, Rio and Herdr are found without asking you to open a new
    shell. Rio is then opened in ~/repos with Herdr already running, using that
    PowerShell 7 executable.
    - Writes a transcript of the run to %LOCALAPPDATA%\skoop\install-<timestamp>.log
      (-LogPath overrides it, -NoLog opts out); the pwsh re-launch shares that file.
      PowerShell 5.1 transcripts capture the script's own messages but not native
      command stdout (e.g. Scoop/gh), so log details are fullest under pwsh.

.PARAMETER RepoRawBase
    Raw URL base used to fetch scoop.json / profile.ps1 when the script is piped in
    and there is no local checkout. Override this if you use a fork.

.PARAMETER ForceUniKey
    Install the Scoop UniKey package even if another UniKey is already installed.

.PARAMETER ForceInstall
    Re-import Scoop apps that are already installed instead of skipping them on
    a re-run (also $env:SKOOP_FORCE_INSTALL=1 for piped runs). Alias: -Force.

.PARAMETER SkipGhLogin
    Skip the interactive `gh auth login` prompt; only wire up an existing gh login.

.PARAMETER HerdrPeer
    Switch: use the interactive gum picker to choose the Herdr machine
    (no value needed). Use -Peer to supply a name/IP non-interactively.

.PARAMETER Peer
    Tailnet IP or MagicDNS name of the Herdr machine. Skips the picker.
    Defaults to $env:SKOOP_HERDR_PEER for piped runs.

.PARAMETER HerdrUser
    SSH user to use on the Herdr machine (otherwise auto-detected).

.PARAMETER SkipHerdrConnect
    Do not run the Herdr remote step (useful for unattended installs).

.PARAMETER Menu
    Open the interactive setup menu (gum when available, numbered prompt
    otherwise). The default is a direct Full setup with no menu (also
    $env:SKOOP_MENU=1 for piped runs).

.PARAMETER NoMenu
    Kept for compatibility; the menu is opt-in now, so a bare `.\install.ps1`
    already runs the full setup without asking.

.PARAMETER EssentialsOnly
    Stop after the Tailscale phase: PowerShell 7, Rio, Vicinae, the Herdr TUI,
    Tailscale sign-in and the acer-ubuntu restore, with their setup finished.
    Run the script again without this switch to install the remaining phases.

.PARAMETER NoGum
    Force the numbered prompt instead of gum (or set $env:SKOOP_NO_GUM=1). Useful
    in terminals where gum cannot draw its TUI.

.PARAMETER NoPwsh
    Do not re-launch under PowerShell 7. Stays on Windows PowerShell 5.1 (also
    $env:SKOOP_NO_PWSH=1).

.PARAMETER NoAutoHerdr
    Do not open Rio with Herdr after the essentials phase (also
    $env:SKOOP_NO_AUTO_HERDR=1). Useful for unattended installs.

.PARAMETER MouseDpi
    Hardware DPI to set on a Logitech HID++ mouse after installing skoopub-mouse
    (default 1200; also $env:SKOOP_MOUSE_DPI). Ignored with -SkipMouseDpi.

.PARAMETER SkipMouseDpi
    Do not touch the mouse DPI (also $env:SKOOP_NO_MOUSE_DPI=1).

.PARAMETER SkipSshRestore
    Do not restore the SSH key from acer-ubuntu (also
    $env:SKOOP_NO_SSH_RESTORE=1).

.PARAMETER SkipRepoClones
    Do not clone the repos registered in manifests/repos.json into ~/repos
    (also $env:SKOOP_NO_REPO_CLONES=1).

.PARAMETER ForceFirefoxRestore
    Repeat the one-time Firefox profile restore from the acer-ubuntu backup even
    when the marker exists (also $env:SKOOP_FORCE_FIREFOX_RESTORE=1). Firefox is
    closed and relaunched around the copy.

.PARAMETER ForceAtuinRestore
    Repeat the one-time Atuin config/history restore (also
    $env:SKOOP_FORCE_ATUIN_RESTORE=1). Close other Atuin shells first.

.PARAMETER SkipFirefoxRestore
    Do not restore the Firefox profile from the backup (also
    $env:SKOOP_NO_FIREFOX_RESTORE=1). Without this switch a failed Firefox
    restore aborts the install before GitHub auth and repo clones.

.PARAMETER SkipAtuinRestore
    Do not restore Atuin config/history from the backup (also
    $env:SKOOP_NO_ATUIN_RESTORE=1).

.PARAMETER LogPath
    File to record the console output in. Defaults to
    %LOCALAPPDATA%\skoop\install-<timestamp>.log; the pwsh re-launch appends to
    the same file (also $env:SKOOP_LOG_PATH for piped runs).

.PARAMETER NoLog
    Do not write a log (also $env:SKOOP_NO_LOG=1).

.PARAMETER ThrottleLimit
    Maximum number of app imports running at once inside each phase (default 4;
    also $env:SKOOP_THROTTLE). 1 runs them sequentially; Windows PowerShell 5.1
    always runs sequentially. Phase order itself never changes.

.EXAMPLE
    # One command: configure this machine, then pick a tailnet machine and add it to Herdr.
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1

.EXAMPLE
    # Force the interactive peer picker.
    .\install.ps1 -HerdrPeer

    # Same, but with the machine/user supplied so nothing is prompted.
    .\install.ps1 -Peer <machine> -HerdrUser <user> -SkipGhLogin

